import test from 'node:test';
import assert from 'node:assert/strict';
import express from 'express';
import pg from 'pg';
import {once} from 'node:events';
import {randomUUID} from 'node:crypto';
import {readFile} from 'node:fs/promises';
import {mountSolarFit} from '../solarfit-routes.js';
test('SolarFit HTTP workflow with a real PostgreSQL transaction and synthetic approved survey',async t=>{
 const db=new pg.Pool({connectionString:process.env.TEST_DATABASE_URL}); t.after(()=>db.end());
 if(!process.env.TEST_DATABASE_URL)throw Error('Disposable TEST_DATABASE_URL required');
 assert.equal((await db.query("SELECT to_regnamespace('photonix_solarfit') AS schema")).rows[0].schema,null);
 await db.query(await readFile(new URL('../solarfit-schema.sql',import.meta.url),'utf8'));
 const lead={id:1,surveyStatus:'pending',usableRoofArea:350,budget:5000,monthlyBill:2320,backupRequired:'none',propertyType:'residential'};
 const sales=randomUUID(),manager=randomUUID(),app=express();app.use(express.json());
 mountSolarFit(app,(req,_res,next)=>{req.actor=req.get('Role')==='manager'?{role:'manager',id:manager}:{role:'sales',id:sales};next()},db,{getEnquiry:async()=>lead});
 const server=app.listen(0,'127.0.0.1');await once(server,'listening');t.after(()=>new Promise(r=>server.close(r)));
 const post=(path,body={},role='sales')=>fetch('http://127.0.0.1:'+server.address().port+'/api/solarfit/'+path,{method:'POST',headers:{'Content-Type':'application/json',Role:role},body:JSON.stringify(body)});
 assert.equal((await post('leads/1/quote',{packageId:'kit'})).status,409);
 const kit={id:'kit',kw:3,type:'on-grid',roofM2:22,taxPct:5,estimatedResidentialSubsidyPaise:0,lines:[{productId:1,qty:2,unitCostPaise:95,unitSellPaise:100}]};
 await db.query('INSERT INTO photonix_solarfit.catalog(packages,assumptions) VALUES($1,$2)',[JSON.stringify([kit]),{monthlyKwhPerKw:100,tariffPaisePerKwh:800,minimumMarginPct:20}]);
 await db.query('INSERT INTO photonix_solarfit.approved_survey(lead_id,revision,needs,approved_by) VALUES(1,$1,$2,$3)',['v1',{monthlyKwh:290,usableRoofM2:30,budgetPaise:500000,propertyType:'residential',backup:false},randomUUID()]);
 lead.surveyStatus='approved';
 const quote=await(await post('leads/1/quote',{packageId:'kit'})).json();assert.ok(quote.id);
 const path='quotes/'+quote.id, consent={acceptanceReference:'synthetic signed acceptance'};
 assert.equal((await post(path+'/accept',consent)).status,409);
 assert.equal((await post(path+'/review',{reason:'demo review'})).status,403);
 assert.equal((await post(path+'/review',{reason:'demo review'},'manager')).status,200);
 kit.lines[0].unitCostPaise++;await db.query('UPDATE photonix_solarfit.catalog SET packages=$1',[JSON.stringify([kit])]);
 assert.equal((await post(path+'/accept',consent)).status,409);
 kit.lines[0].unitCostPaise--;await db.query('UPDATE photonix_solarfit.catalog SET packages=$1',[JSON.stringify([kit])]);
 const results=await Promise.all([post(path+'/accept',consent),post(path+'/accept',consent)]);
 assert.deepEqual(results.map(r=>r.status),[200,200]);assert.deepEqual(await results[0].json(),await results[1].json());
 assert.equal((await db.query('SELECT * FROM photonix_solarfit.confirmed_order')).rowCount,1);
});